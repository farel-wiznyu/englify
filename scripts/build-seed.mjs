// Generates supabase/seed.sql from src/data/vocabulary.json (+ audio-manifest.json when present).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync(new URL('../src/data/vocabulary.json', import.meta.url), 'utf8'));
const manifestUrl = new URL('../src/data/audio-manifest.json', import.meta.url);
const manifest = existsSync(manifestUrl) ? JSON.parse(readFileSync(manifestUrl, 'utf8')) : {};

const q = (v) => (v == null ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const lines = ['-- Generated by scripts/build-seed.mjs. Do not edit by hand.', 'begin;'];

data.categories.forEach((c, i) =>
  lines.push(
    `insert into public.categories (id, name, name_id, emoji, color_token, sort_order) values (${q(c.id)}, ${q(c.name)}, ${q(c.nameId)}, ${q(c.emoji)}, ${q(c.color)}, ${i}) on conflict (id) do update set name = excluded.name, name_id = excluded.name_id, emoji = excluded.emoji, color_token = excluded.color_token, sort_order = excluded.sort_order;`,
  ),
);

data.items.forEach((v, i) =>
  lines.push(
    `insert into public.vocabulary_items (id, category_id, word, translation, emoji, example_sentence, audio_url, sort_order) values (${q(v.id)}, ${q(v.categoryId)}, ${q(v.word)}, ${q(v.translation)}, ${q(v.emoji)}, ${q(v.example)}, ${q(manifest[v.id])}, ${i}) on conflict (id) do update set word = excluded.word, translation = excluded.translation, emoji = excluded.emoji, example_sentence = excluded.example_sentence, audio_url = coalesce(excluded.audio_url, public.vocabulary_items.audio_url), sort_order = excluded.sort_order;`,
  ),
);

data.lessons.forEach((l, i) => {
  lines.push(
    `insert into public.lessons (id, category_id, title, estimated_minutes, sort_order) values (${q(l.id)}, ${q(l.categoryId)}, ${q(l.title)}, ${l.estimatedMinutes}, ${i}) on conflict (id) do update set title = excluded.title, estimated_minutes = excluded.estimated_minutes, sort_order = excluded.sort_order;`,
  );
  l.itemIds.forEach((itemId, j) =>
    lines.push(
      `insert into public.lesson_items (lesson_id, vocabulary_item_id, sort_order) values (${q(l.id)}, ${q(itemId)}, ${j}) on conflict do nothing;`,
    ),
  );
});

lines.push('commit;');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n') + '\n');
console.log(`seed.sql written (${data.items.length} items, ${Object.keys(manifest).length} with audio)`);
